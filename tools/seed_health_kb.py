    before = len(memory.get_all_rag_entries())
    ok, fail = 0, 0
    for i, text in enumerate(ENTRIES, 1):
        try:
            if rag.add_to_knowledge_base(text):
                ok += 1
                print(f"[知识库] {i}/{len(ENTRIES)} 已录入：{text[:24]}…")
            else:
                fail += 1
                print(f"[知识库] {i} 向量化失败（跳过）：{text[:24]}…")
        except Exception as e:
            fail += 1
            print(f"[知识库] {i} 入库异常：{e}")
