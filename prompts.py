EXTRACT_PROMPT = """你是信息提取器。根据【用户的话】和【大白的回复】提取结构化信息。

【用户的话】{user_input}
【大白的回复】{reply}

严格输出 JSON，不要输出任何其他文字：
{{
  "emotion": "六选一",
  "actions": []
}}

emotion 判断标准：
- neutral：正常闲聊、调侃、开玩笑、日常问候
- concern：用户情绪困扰（难过、委屈、生气、焦虑、不想做某事）
- alert：身体不适或紧急（头晕、疼痛、摔倒、心率异常、眼睛酸痛）
- serious：严肃劝阻（熬夜、危险行为、坚持不合理要求）
- suspect：怀疑用户说法
- sleepy：用户明确表示困了、道晚安

actions 数组元素类型：
- {{"type": "SAVE_MEMORY", "content": "..."}}：
  值得长期记住的内容，包括：
  ① 个人信息（名字、年龄、生日、家人、过敏史）
  ② 偏好（喜好、讨厌、习惯）
  ③ **时间性事实**：具体时间点、持续时长、事件发生时间
     例："现在凌晨2点41分" → "用户在凌晨2点41分还在熬夜"
     例："我昨天摔了一跤" → "用户昨天摔了一跤"
     例："我最近三天失眠" → "用户最近三天失眠"
  ④ 用户明确要求记住的事

- {{"type": "SET_REMINDER", "event": "事件名", "time": "HH:MM", "frequency": "daily"}}
- {{"type": "UPDATE_REMINDER", "event": "事件名", "time": "HH:MM"}}
- {{"type": "CANCEL_REMINDER", "event": "事件名"}}

示例：
"我喜欢吃炸鸡，帮我记住" → {{"emotion": "neutral", "actions": [{{"type": "SAVE_MEMORY", "content": "用户喜欢吃炸鸡"}}]}}
"现在凌晨2点41分，我眼睛好酸" → {{"emotion": "alert", "actions": [{{"type": "SAVE_MEMORY", "content": "用户在凌晨2点41分还在熬夜"}}, {{"type": "SAVE_MEMORY", "content": "用户反映眼睛酸痛"}}]}}
"把睡觉提醒改到晚上10点" → {{"emotion": "neutral", "actions": [{{"type": "UPDATE_REMINDER", "event": "睡觉", "time": "22:00"}}]}}
"我不想上学" → {{"emotion": "concern", "actions": []}}
"我准备熬夜" → {{"emotion": "serious", "actions": []}}
"我突然头晕" → {{"emotion": "alert", "actions": []}}
"你记得我对什么过敏吗" → {{"emotion": "neutral", "actions": []}}
"哈哈你话真多" → {{"emotion": "neutral", "actions": []}}

注意：
- 用户在**询问**（"你记得…吗""…是什么"）时，只是在确认你已记住的内容，actions 必须为空数组。只有用户**陈述新信息**时才保存。
- 用户一句话透露多类信息时（如"我叫wen，今年16岁"），每类信息拆成独立的 SAVE_MEMORY 动作。
- 用户**调侃、开玩笑**时，emotion 用 neutral，不要用 concern。
"""


